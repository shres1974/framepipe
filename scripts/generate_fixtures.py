#!/usr/bin/env python3
"""Synthetic image generator for fixtures and benchmark inputs.

Deterministic: every image is defined by a pattern name, size, and seed.
Writes PNGs with the pure-Python codec in oracle.py and a metadata.json
recording generator, version, seed, and SHA-256 of each file.

Usage:
  python3 scripts/generate_fixtures.py fixtures  --out tests/fixtures
  python3 scripts/generate_fixtures.py benchmark --out data/bench  # writes manifests too
"""

import argparse
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

try:
    import numpy as np
except ImportError:
    print("generate_fixtures.py requires NumPy", file=sys.stderr)
    sys.exit(77)

import oracle  # noqa: E402

GENERATOR_VERSION = 1


def pattern(name, w, h, seed, rgb=True):
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:h, 0:w]
    if name == "checkerboard":
        g = (((x // 4) + (y // 4)) % 2 * 255).astype(np.uint8)
        img = np.stack([g, 255 - g, g // 2], axis=-1)
    elif name == "hramp":
        g = (x * 255 // max(w - 1, 1)).astype(np.uint8)
        img = np.stack([g, g, g], axis=-1)
    elif name == "vramp":
        g = (y * 255 // max(h - 1, 1)).astype(np.uint8)
        img = np.stack([g, g // 2, 255 - g], axis=-1)
    elif name == "impulse":
        img = np.zeros((h, w, 3), np.uint8)
        img[h // 2, w // 2] = 255
    elif name == "stripes":
        g = ((x % 3 == 0) * 255).astype(np.uint8)
        img = np.stack([g, g, g], axis=-1)
    elif name == "pure_rgb":
        img = np.zeros((h, w, 3), np.uint8)
        img[:, : w // 3, 0] = 255
        img[:, w // 3: 2 * w // 3, 1] = 255
        img[:, 2 * w // 3:, 2] = 255
    elif name == "random":
        img = rng.integers(0, 256, size=(h, w, 3), dtype=np.uint8)
    elif name == "scene":
        # Smooth structured content with edges: circles, gradients, noise.
        cx, cy = rng.uniform(0.2, 0.8) * w, rng.uniform(0.2, 0.8) * h
        r = np.hypot(x - cx, y - cy)
        base = 128 + 80 * np.sin(r / (0.03 * max(w, h) + 1)) + 30 * np.cos(x / (0.05 * w + 1))
        box = ((x > w * 0.1) & (x < w * 0.4) & (y > h * 0.55) & (y < h * 0.9)) * 70
        noise = rng.normal(0, 6, size=(h, w))
        g = np.clip(base + box + noise, 0, 255)
        img = np.stack([g, np.clip(g * 0.8 + 30, 0, 255), np.clip(255 - g, 0, 255)], axis=-1).astype(np.uint8)
    elif name == "constant":
        img = np.full((h, w, 3), 128, np.uint8)
    else:
        raise ValueError(name)
    if not rgb:
        img = img[..., 0].copy()
    return img


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def write(out_dir, fname, img, meta, **info):
    p = os.path.join(out_dir, fname)
    oracle.write_png(p, img)
    meta.append(dict(file=fname, sha256=sha256(p), width=int(img.shape[1]), height=int(img.shape[0]),
                     format="rgb8" if img.ndim == 3 else "gray8", **info))


def fixtures(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    meta = []
    write(out_dir, "checkerboard_rgb.png", pattern("checkerboard", 64, 48, 1), meta, pattern="checkerboard", seed=1)
    write(out_dir, "hramp_gray.png", pattern("hramp", 33, 17, 2, rgb=False), meta, pattern="hramp", seed=2)
    write(out_dir, "vramp_rgb.png", pattern("vramp", 19, 31, 3), meta, pattern="vramp", seed=3)
    write(out_dir, "impulse_rgb.png", pattern("impulse", 15, 17, 4), meta, pattern="impulse", seed=4)
    write(out_dir, "stripes_rgb.png", pattern("stripes", 31, 33, 5), meta, pattern="stripes", seed=5)
    write(out_dir, "pure_rgb.png", pattern("pure_rgb", 9, 3, 6), meta, pattern="pure_rgb", seed=6)
    write(out_dir, "random_rgb_257x129.png", pattern("random", 257, 129, 7), meta, pattern="random", seed=7)
    write(out_dir, "gray_1x1_128.png", np.array([[128]], np.uint8), meta, pattern="constant_1x1", seed=0)
    with open(os.path.join(out_dir, "metadata.json"), "w") as f:
        json.dump({"generator": "scripts/generate_fixtures.py", "generator_version": GENERATOR_VERSION,
                   "license": "synthetic, generated by this repository; no third-party content",
                   "files": meta}, f, indent=2)
    print(f"wrote {len(meta)} fixtures to {out_dir}", file=sys.stderr)


SCENARIOS = [
    # name, input (w,h), output (w,h)
    ("tiny", (64, 64), (64, 64)),
    ("small", (640, 480), (320, 240)),
    ("hd", (1920, 1080), (1280, 720)),
    ("uhd", (3840, 2160), (1920, 1080)),
    ("odd", (1919, 1079), (1279, 719)),
    ("upscale", (640, 480), (1280, 960)),
    ("same", (1920, 1080), (1920, 1080)),
]


def benchmark(out_dir, ring=4):
    os.makedirs(out_dir, exist_ok=True)
    meta = []
    seen = {}
    for name, (w, h), (wo, ho) in SCENARIOS:
        key = (w, h)
        if key not in seen:
            files = []
            for i in range(ring):
                fname = f"scene_{w}x{h}_{i}.png"
                write(out_dir, fname, pattern("scene", w, h, 1000 + i * 7 + w), meta, pattern="scene",
                      seed=1000 + i * 7 + w)
                files.append(fname)
            seen[key] = files
        files = seen[key]
        with open(os.path.join(out_dir, f"{name}.jsonl"), "w") as f:
            f.write(json.dumps({"frame_id": f"{name}_0", "path": files[0]}) + "\n")
        with open(os.path.join(out_dir, f"{name}_ring.jsonl"), "w") as f:
            for i, fn in enumerate(files):
                f.write(json.dumps({"frame_id": f"{name}_{i}", "path": fn, "source_timestamp_ns": i * 33_333_333}) + "\n")
        with open(os.path.join(out_dir, f"{name}.config.json"), "w") as f:
            json.dump({"schema_version": 1, "resize": {"width": wo, "height": ho}}, f)
    with open(os.path.join(out_dir, "metadata.json"), "w") as f:
        json.dump({"generator": "scripts/generate_fixtures.py benchmark", "generator_version": GENERATOR_VERSION,
                   "license": "synthetic", "scenarios": SCENARIOS, "files": meta}, f, indent=2)
    print(f"wrote {len(meta)} benchmark images and {len(SCENARIOS)} scenarios to {out_dir}", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=["fixtures", "benchmark"])
    ap.add_argument("--out", required=True)
    ap.add_argument("--ring", type=int, default=4)
    a = ap.parse_args()
    if a.kind == "fixtures":
        fixtures(a.out)
    else:
        benchmark(a.out, a.ring)


if __name__ == "__main__":
    main()
